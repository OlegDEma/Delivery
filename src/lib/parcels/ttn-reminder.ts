/** «Так» → «Поштою», але ТТН не введено: нагадування ще раз після оформлення. */
export const TTN_MISSING_REMINDER =
  'Ви не ввели номер ТТН. Обовʼязково введіть номер ТТН з Вашої накладної Нової пошти (14 цифр) — за ним ми знайдемо Вашу посилку.';

/** Номер ТТН Нової пошти — рівно 14 цифр (пробіли між групами цифр допускаються). */
export function isValidNpTtn(raw: string | null | undefined): boolean {
  return /^\d{14}$/.test((raw ?? '').replace(/\s/g, ''));
}
