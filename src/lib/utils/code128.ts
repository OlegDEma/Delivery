const START_B = 104;
const START_C = 105;
const CODE_B = 100; // перемикання на набір B з набору C
const STOP = 106;

/** Значення символів (без контрольного і STOP) для рядка з друкованих ASCII. */
function encodeValues(text: string): number[] {
  if (!/^[\x20-\x7e]*$/.test(text)) throw new Error('CODE128_UNSUPPORTED_CHAR');
  const lead = text.match(/^\d+/)?.[0] ?? '';
  const cLen = lead.length >= 4 ? lead.length - (lead.length % 2) : 0;
  const values: number[] = [];
  if (cLen > 0) {
    values.push(START_C);
    for (let i = 0; i < cLen; i += 2) values.push(Number(text.slice(i, i + 2)));
    if (cLen < text.length) values.push(CODE_B);
  } else {
    values.push(START_B);
  }
  for (const ch of text.slice(cLen)) values.push(ch.charCodeAt(0) - 32);
  return values;
}

/** Ширини елементів (у модулях) повного штрихкоду: START … дані … контрольний, STOP. */
export function code128Widths(text: string): number[] {
  const values = encodeValues(text);
  const checksum = values.reduce((sum, v, i) => sum + v * (i === 0 ? 1 : i), 0) % 103;
  const all = [...values, checksum, STOP];
  return all.flatMap((v) => PATTERNS[v].split('').map(Number));
}
